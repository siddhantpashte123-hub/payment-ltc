'use client'

import { CheckCircle2, Clock, ExternalLink, ArrowLeft, Loader2, FileDown } from 'lucide-react'
import { Button } from '@/components/ui/button'

interface ReceiptProps {
  type: 'deposit' | 'send'
  amount: number
  counterparty: string
  txHash?: string
  explorer?: string
  status: 'completed' | 'pending'
  /** Optional live status: when true, shows an animated "confirming" progress */
  live?: boolean
  onBack?: () => void
  /** Coin unit label (e.g. 'LTC' or 'SOL'). */
  unit?: string
  /** Explorer name shown on the "View on …" link (SoChain for LTC, Solscan for SOL). */
  explorerLabel?: string
}

export function Receipt({
  type,
  amount,
  counterparty,
  txHash,
  explorer,
  status,
  live,
  onBack,
  unit = 'LTC',
  explorerLabel = 'SoChain',
}: ReceiptProps) {
  const isDeposit = type === 'deposit'
  const isConfirming = status === 'pending' && live

  const downloadPdf = () => {
    const lines = [
      'BlueWallet — Transaction Receipt',
      '==============================',
      '',
      `Type:          ${isDeposit ? 'Deposit' : 'Withdrawal (Send)'}`,
      `Amount:        ${amount.toFixed(8)} ${unit}`,
      `Counterparty:  ${counterparty || '—'}`,
      `Status:        ${status === 'completed' ? 'Completed' : 'Pending'}`,
      `Date:          ${new Date().toLocaleString()}`,
      txHash ? `Tx ID:         ${txHash}` : '',
      explorer ? `Explorer:      ${explorer}` : '',
      '',
      '==============================',
      'Generated by BlueWallet',
    ].filter(Boolean)

    // Build a minimal valid PDF with the receipt text.
    const esc = (s: string) =>
      s.replace(/\\/g, '\\\\').replace(/\(/g, '\\(').replace(/\)/g, '\\)')
    const content = lines.map((l) => `(${esc(l)}) Tj T*`).join('\n')
    const stream = `BT /F1 12 Tf 50 780 Td 16 TL ${content} ET`

    const objs: string[] = []
    objs.push('1 0 obj << /Type /Catalog /Pages 2 0 R >> endobj')
    objs.push('2 0 obj << /Type /Pages /Kids [3 0 R] /Count 1 >> endobj')
    objs.push(
      '3 0 obj << /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 5 0 R >> >> /Contents 4 0 R >> endobj'
    )
    objs.push(`4 0 obj << /Length ${stream.length} >> stream\n${stream}\nendstream endobj`)
    objs.push(
      '5 0 obj << /Type /Font /Subtype /Type1 /BaseFont /Helvetica >> endobj'
    )

    let pdf = '%PDF-1.4\n'
    const offsets: number[] = []
    objs.forEach((o, i) => {
      offsets.push(pdf.length)
      pdf += `${i + 1} 0 obj\n${o}\nendobj\n`
    })
    const xrefStart = pdf.length
    pdf += `xref\n0 ${objs.length + 1}\n`
    pdf += '0000000000 65535 f \n'
    offsets.forEach((off) => {
      pdf += `${String(off).padStart(10, '0')} 00000 n \n`
    })
    pdf += `trailer << /Size ${objs.length + 1} /Root 1 0 R >>\nstartxref\n${xrefStart}\n%%EOF`

    const blob = new Blob([pdf], { type: 'application/pdf' })
    const url = URL.createObjectURL(blob)
    const a = document.createElement('a')
    a.href = url
    a.download = `bluewallet-receipt-${Date.now()}.pdf`
    a.click()
    URL.revokeObjectURL(url)
  }

  return (
    <div className="glass-panel p-8 md:p-10 max-w-xl mx-auto text-center relative overflow-hidden">
      {/* Top accent glow */}
      <div className="absolute -top-24 left-1/2 -translate-x-1/2 w-64 h-64 rounded-full bg-emerald-500/10 blur-3xl pointer-events-none" />

      <div className="relative z-10 flex flex-col items-center gap-5">
        {/* Animated check / clock */}
        <div className="animate-pop">
          {status === 'completed' ? (
            <div className="w-20 h-20 rounded-full bg-emerald-500/10 border border-emerald-500/30 flex items-center justify-center">
              <CheckCircle2 size={44} className="text-emerald-400" />
            </div>
          ) : isConfirming ? (
            <div className="w-20 h-20 rounded-full bg-amber-500/10 border border-amber-500/30 flex items-center justify-center">
              <Loader2 size={44} className="text-amber-400 animate-spin" />
            </div>
          ) : (
            <div className="w-20 h-20 rounded-full bg-amber-500/10 border border-amber-500/30 flex items-center justify-center">
              <Clock size={44} className="text-amber-400" />
            </div>
          )}
        </div>

        <div>
          <h2 className="text-2xl font-bold text-white tracking-tight">
            {status === 'completed'
              ? 'Payment Complete'
              : isConfirming
              ? 'Confirming…'
              : 'Payment Submitted'}
          </h2>
          <p className="text-white/50 text-sm mt-1">
            {isDeposit ? 'Deposit received' : `${unit} sent`} — your receipt
          </p>
        </div>

        {isConfirming && (
          <div className="w-full max-w-xs">
            <div className="h-1.5 bg-white/10 rounded-full overflow-hidden">
              <div className="h-full bg-amber-400 rounded-full animate-pulse w-2/3" />
            </div>
            <p className="text-xs text-amber-300/80 mt-2">
              Waiting for on-chain confirmation. This page updates automatically.
            </p>
          </div>
        )}

        {/* Amount */}
        <div className="w-full bg-white/5 border border-white/10 rounded-2xl px-6 py-5">
          <p className="text-xs text-white/40 uppercase tracking-wider mb-1">
            Amount
          </p>
          <p className="text-3xl font-bold text-white tracking-tight">
            {amount.toFixed(8)} <span className="text-lg text-white/50">{unit}</span>
          </p>
        </div>

        {/* Details */}
        <div className="w-full space-y-3 text-left">
          <DetailRow label="Counterparty" value={counterparty || '—'} />
          {txHash && <DetailRow label="Transaction ID" value={txHash} mono />}
          {explorer && (
            <div className="flex items-center justify-between gap-3 bg-white/5 border border-white/10 rounded-xl px-4 py-3">
              <span className="text-xs text-white/40 uppercase tracking-wider">
                Explorer
              </span>
              <a
                href={explorer}
                target="_blank"
                rel="noopener noreferrer"
                className="inline-flex items-center gap-1.5 text-xs font-medium text-emerald-400 hover:text-emerald-300 transition-colors"
              >
                View on {explorerLabel}
                <ExternalLink size={12} />
              </a>
            </div>
          )}
        </div>

        <Button
          onClick={downloadPdf}
          variant="outline"
          className="w-full mt-2"
        >
          <FileDown size={16} className="mr-2" />
          Download Receipt (PDF)
        </Button>

        {onBack && (
          <Button
            onClick={onBack}
            variant="outline"
            className="w-full mt-2"
          >
            <ArrowLeft size={16} className="mr-2" />
            Back to Dashboard
          </Button>
        )}
      </div>
    </div>
  )
}

function DetailRow({
  label,
  value,
  mono,
}: {
  label: string
  value: string
  mono?: boolean
}) {
  return (
    <div className="flex items-center justify-between gap-3 bg-white/5 border border-white/10 rounded-xl px-4 py-3">
      <span className="text-xs text-white/40 uppercase tracking-wider">
        {label}
      </span>
      <span
        className={`text-xs text-white truncate max-w-[60%] ${
          mono ? 'font-mono' : ''
        }`}
      >
        {value}
      </span>
    </div>
  )
}
